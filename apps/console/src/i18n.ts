type KeyLabels = ReturnType<typeof keyLabels>;

export type Strings = (typeof STRINGS)['fr'];

/** Langue effective de la console, à jour en temps réel. */
export function useLang(): Lang {
  const { language } = useSettings();
  return language === 'auto' ? detectLang() : language;
}

/** Textes de la console dans la langue effective. */
export function useT(): Strings {
  return STRINGS[useLang()];
}

/** Touches du clavier à afficher (disposition et langue effectives). */
export function useKeyLabels(): KeyLabels {
  return keyLabels(useKeyboardLayout(), useLang());
}
